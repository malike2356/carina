export type PsppAnalysisType =
  | 'descriptive'
  | 'ttest'
  | 'anova'
  | 'chi-square'
  | 'correlation'
  | 'regression'
  | 'nonparametric'
  | 'factor';

export interface SyntaxRequestOptions {
  posthoc?: 'bonferroni' | 'tukey' | 'none';
  normality?: boolean;
  effectSize?: boolean;
  missingListwise?: boolean;
}

export interface SyntaxRequest {
  dataFile: string;
  analysisType: PsppAnalysisType;
  variables?: string[];
  groupBy?: string;
  dependentVar?: string;
  independentVars?: string[];
  options?: SyntaxRequestOptions;
}

function quoteSpssPath(filePath: string): string {
  return `'${filePath.replace(/'/g, "''")}'`;
}

function varList(variables: string[] | undefined): string {
  return variables?.join(' ') ?? '';
}

export function generateSyntax(req: SyntaxRequest): string {
  const lines: string[] = [
    '* PSPP syntax generated by Carina',
    `* Analysis: ${req.analysisType}`,
    `* Generated at: ${new Date().toISOString()}`,
    '',
    `GET FILE=${quoteSpssPath(req.dataFile)}.`,
    'DATASET NAME DataSet1 WINDOW=FRONT.',
    '',
  ];

  switch (req.analysisType) {
    case 'descriptive':
      lines.push(
        `DESCRIPTIVES VARIABLES=${varList(req.variables)}`,
        '  /STATISTICS=MEAN STDDEV MIN MAX SEMEAN KURTOSIS SKEWNESS.',
        '',
        `FREQUENCIES VARIABLES=${varList(req.variables)}`,
        '  /STATISTICS=MEDIAN MODE',
        '  /HISTOGRAM NORMAL',
        '  /ORDER=ANALYSIS.',
      );
      break;

    case 'ttest':
      lines.push(
        `T-TEST GROUPS=${req.groupBy}(1,2)`,
        '  /MISSING=ANALYSIS',
        `  /VARIABLES=${varList(req.variables)}`,
        '  /ES DISPLAY(TRUE).',
      );
      if (req.options?.effectSize) {
        lines.push('  /CRITERIA=CI(.95).');
      }
      break;

    case 'anova':
      lines.push(
        `ONEWAY ${varList(req.variables)} BY ${req.groupBy}`,
        '  /MISSING ANALYSIS.',
      );
      if (req.options?.posthoc && req.options.posthoc !== 'none') {
        const test = req.options.posthoc === 'bonferroni' ? 'BONFERRONI' : 'TUKEY';
        lines.push(`  /POSTHOC=${test} ALPHA(0.05).`);
      }
      if (req.options?.effectSize) {
        lines.push('  /STATISTICS EFFECTS.');
      }
      break;

    case 'chi-square':
      lines.push(
        'CROSSTABS',
        `  /TABLES=${req.variables?.[0]} BY ${req.variables?.[1]}`,
        '  /FORMAT=AVALUE TABLES',
        '  /STATISTICS=CHISQ PHI',
        '  /CELLS=COUNT EXPECTED ROW COLUMN TOTAL',
        '  /COUNT ROUND CELL.',
      );
      break;

    case 'correlation':
      lines.push(
        'CORRELATIONS',
        `  /VARIABLES=${varList(req.variables)}`,
        '  /PRINT=TWOTAIL NOSIG',
        '  /MISSING=PAIRWISE.',
      );
      break;

    case 'regression':
      lines.push(
        'REGRESSION',
        '  /MISSING LISTWISE',
        '  /STATISTICS COEFF OUTS R ANOVA',
        '  /CRITERIA=PIN(.05) POUT(.10)',
        '  /NOORIGIN',
        `  /DEPENDENT ${req.dependentVar}`,
        `  /METHOD=ENTER ${req.independentVars?.join(' ') ?? ''}.`,
      );
      break;

    case 'nonparametric':
      lines.push(
        'NPAR TESTS',
        `  /M-W= ${varList(req.variables)} BY ${req.groupBy}(1 2)`,
        '  /MISSING ANALYSIS.',
      );
      break;

    case 'factor':
      lines.push(
        'FACTOR',
        `  /VARIABLES ${varList(req.variables)}`,
        '  /MISSING LISTWISE',
        `  /ANALYSIS ${varList(req.variables)}`,
        '  /PRINT INITIAL EXTRACTION ROTATION',
        '  /CRITERIA MINEIGEN(1) ITERATE(25)',
        '  /EXTRACTION PC',
        '  /ROTATION VARIMAX.',
      );
      break;

    default:
      throw new Error(`Unsupported analysis type: ${req.analysisType as string}`);
  }

  return lines.join('\n');
}
