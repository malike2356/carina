export type RAnalysisType =
  | 'descriptive'
  | 'ttest'
  | 'anova'
  | 'correlation'
  | 'regression'
  | 'chi-square'
  | 'factor'
  | 'reliability';

export interface RScriptRequest {
  dataFile: string;
  analysisType: RAnalysisType;
  variables: string[];
  groupBy?: string;
  dependentVar?: string;
  independentVars?: string[];
  apaFormat?: boolean;
}

function quoteList(items: string[]): string {
  return items.map((value) => `"${value.replace(/"/g, '\\"')}"`).join(', ');
}

export function generateRScript(params: RScriptRequest): string {
  const independents = params.independentVars?.length
    ? params.independentVars
    : params.variables;

  const lines = [
    '# R analysis script generated by Carina',
    `# Analysis: ${params.analysisType}`,
    `# Generated: ${new Date().toISOString()}`,
    '',
    'library(haven)',
    'library(dplyr)',
    'library(tidyr)',
    'library(broom)',
  ];

  if (params.apaFormat) {
    lines.push('suppressPackageStartupMessages({ if (requireNamespace("apaTables", quietly=TRUE)) library(apaTables) })');
  }

  lines.push(
    '',
    `df <- read_sav("${params.dataFile.replace(/"/g, '\\"')}")`,
    'cat("Data loaded:", nrow(df), "rows,", ncol(df), "columns\\n")',
    '',
  );

  switch (params.analysisType) {
    case 'descriptive':
      lines.push(
        `vars <- c(${quoteList(params.variables)})`,
        'desc <- psych::describe(df[, vars, drop=FALSE])',
        'print(desc)',
      );
      break;
    case 'ttest':
      lines.push(
        `for (var in c(${quoteList(params.variables)})) {`,
        `  cat("\\n--- T-test for", var, "---\\n")`,
        `  print(t.test(as.formula(paste(var, "~", "${params.groupBy}")), data = df))`,
        '}',
      );
      break;
    case 'anova':
      lines.push(
        `for (var in c(${quoteList(params.variables)})) {`,
        `  cat("\\n--- ANOVA for", var, "---\\n")`,
        `  model <- aov(as.formula(paste(var, "~", "${params.groupBy}")), data = df)`,
        '  print(summary(model))',
        '  print(TukeyHSD(model))',
        '}',
      );
      break;
    case 'regression':
      lines.push(
        `formula <- as.formula(paste("${params.dependentVar} ~", paste(c(${quoteList(independents)}), collapse = " + ")))`,
        'model <- lm(formula, data = df)',
        'print(summary(model))',
        'print(tidy(model))',
      );
      break;
    case 'correlation':
      lines.push(
        `cor_matrix <- cor(df[, c(${quoteList(params.variables)})], use = "pairwise.complete.obs")`,
        'print(round(cor_matrix, 3))',
      );
      break;
    case 'chi-square':
      lines.push(
        `var1 <- c(${quoteList(params.variables)})[1]`,
        `var2 <- c(${quoteList(params.variables)})[2]`,
        'tbl <- table(df[[var1]], df[[var2]])',
        'print(tbl)',
        'print(chisq.test(tbl))',
      );
      break;
    case 'factor':
      lines.push(
        'library(psych)',
        `fa_result <- fa(df[, c(${quoteList(params.variables)})], nfactors = 1, rotate = "varimax")`,
        'print(fa_result$loadings, cutoff = 0.3)',
      );
      break;
    case 'reliability':
      lines.push(
        'library(psych)',
        `alpha_result <- alpha(df[, c(${quoteList(params.variables)})])`,
        'print(alpha_result$total)',
      );
      break;
    default:
      throw new Error(`Unsupported R analysis type: ${params.analysisType as string}`);
  }

  return lines.join('\n');
}
