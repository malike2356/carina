import { pool } from '../db.js';
import type { AuditLogRow, AuditEventType, AuditSeverity } from './audit-schemas.js';

export interface AuditSearchParams {
  tenant_id?: string;
  event_type?: AuditEventType;
  severity?: AuditSeverity;
  from?: string; // ISO date string
  to?: string;   // ISO date string
  query?: string; // free-text search against action and detail
  page?: number;
  per_page?: number;
}

export interface AuditSearchResult {
  events: AuditLogRow[];
  total: number;
  page: number;
  per_page: number;
}

function serializeRow(row: Record<string, unknown>): AuditLogRow {
  return {
    id: row.id as string,
    tenant_id: row.tenant_id as string,
    event_type: row.event_type as AuditEventType,
    action: row.action as string,
    detail: typeof row.detail === 'object' && row.detail !== null
      ? row.detail as Record<string, unknown>
      : typeof row.detail === 'string'
        ? (() => { try { return JSON.parse(row.detail as string); } catch { return {}; } })()
        : {},
    severity: row.severity as AuditSeverity,
    session_id: row.session_id as string | null,
    ip_address: row.ip_address as string | null,
    admin_email: row.admin_email as string | null,
    timestamp: new Date(row.timestamp as string).toISOString(),
  };
}

export async function searchAuditLog(params: AuditSearchParams): Promise<AuditSearchResult> {
  const page = Math.max(1, params.page ?? 1);
  const perPage = Math.min(500, Math.max(1, params.per_page ?? 50));
  const offset = (page - 1) * perPage;

  const conditions: string[] = [];
  const values: unknown[] = [];
  let paramIdx = 0;

  if (params.tenant_id) {
    paramIdx++;
    conditions.push(`tenant_id = $${paramIdx}`);
    values.push(params.tenant_id);
  }

  if (params.event_type) {
    paramIdx++;
    conditions.push(`event_type = $${paramIdx}`);
    values.push(params.event_type);
  }

  if (params.severity) {
    paramIdx++;
    conditions.push(`severity = $${paramIdx}`);
    values.push(params.severity);
  }

  if (params.from) {
    paramIdx++;
    conditions.push(`timestamp >= $${paramIdx}::timestamptz`);
    values.push(params.from);
  }

  if (params.to) {
    paramIdx++;
    conditions.push(`timestamp <= $${paramIdx}::timestamptz`);
    values.push(params.to);
  }

  if (params.query && params.query.trim()) {
    paramIdx++;
    const q = `%${params.query.trim()}%`;
    conditions.push(
      `(action ILIKE $${paramIdx} OR detail::text ILIKE $${paramIdx})`,
    );
    values.push(q);
  }

  const whereClause = conditions.length > 0
    ? `WHERE ${conditions.join(' AND ')}`
    : '';

  // Count total matching rows
  const countResult = await pool.query<{ total: string }>(
    `SELECT COUNT(*) AS total FROM audit_log ${whereClause}`,
    values,
  );

  const total = parseInt(countResult.rows[0]?.total ?? '0', 10);

  // Fetch paginated rows
  paramIdx++;
  values.push(perPage);
  paramIdx++;
  values.push(offset);

  const dataResult = await pool.query<Record<string, unknown>>(
    `SELECT id, tenant_id, event_type, action, detail, severity,
            session_id, ip_address, admin_email, timestamp
     FROM audit_log
     ${whereClause}
     ORDER BY timestamp DESC
     LIMIT $${paramIdx - 1}
     OFFSET $${paramIdx}`,
    values,
  );

  return {
    events: dataResult.rows.map(serializeRow),
    total,
    page,
    per_page: perPage,
  };
}

/**
 * Generate a minimal PDF document from audit log rows.
 *
 * Since the project does not depend on a PDF library, we produce a
 * lightweight text-based PDF using hand-crafted PDF syntax. This
 * avoids adding a new dependency for a rarely-used export format
 * while still providing a genuine PDF output option.
 */
export async function exportAuditPdf(events: AuditLogRow[]): Promise<Buffer> {
  const lines: string[] = [];

  // PDF header
  lines.push('%PDF-1.4');

  // Object 1: Catalog
  lines.push('1 0 obj');
  lines.push('<< /Type /Catalog /Pages 2 0 R >>');
  lines.push('endobj');

  // Object 2: Pages
  lines.push('2 0 obj');
  lines.push('<< /Type /Pages /Kids [3 0 R] /Count 1 >>');
  lines.push('endobj');

  // Build page content stream
  const contentLines: string[] = [];
  contentLines.push('BT');
  contentLines.push('/F1 10 Tf');
  contentLines.push('72 750 Td');
  contentLines.push(`(Audit Log Export - ${new Date().toISOString().slice(0, 10)}) Tj`);
  contentLines.push('0 -18 Td');
  contentLines.push('(Generated by Labyrinth Scout Console) Tj');
  contentLines.push('0 -24 Td');

  // Table headers
  contentLines.push('/F1 8 Tf');
  contentLines.push(
    '(ID | Tenant | Type | Action | Severity | Timestamp) Tj',
  );
  contentLines.push('0 -14 Td');

  // Row data (max ~40 rows to fit one page)
  const displayEvents = events.slice(0, 40);
  for (const event of displayEvents) {
    const ts = event.timestamp.slice(0, 19).replace('T', ' ');
    const rowText = `${event.id.slice(0, 8)} | ${event.tenant_id.slice(0, 10)} | ${event.event_type} | ${event.action.slice(0, 20)} | ${event.severity} | ${ts}`;
    // Escape PDF string special chars
    const escaped = rowText
      .replace(/\\/g, '\\\\')
      .replace(/\(/g, '\\(')
      .replace(/\)/g, '\\)');
    contentLines.push(`(${escaped}) Tj`);
    contentLines.push('0 -12 Td');
  }

  if (events.length > 40) {
    contentLines.push(`(... and ${events.length - 40} more rows) Tj`);
  }

  contentLines.push('ET');

  const contentStream = contentLines.join('\n');

  // Object 3: Page
  lines.push('3 0 obj');
  lines.push('<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792]');
  lines.push(`   /Contents 4 0 R`);
  lines.push('   /Resources << /Font << /F1 5 0 R >> >>');
  lines.push('>>');
  lines.push('endobj');

  // Object 4: Content stream
  lines.push('4 0 obj');
  lines.push(`<< /Length ${contentStream.length} >>`);
  lines.push('stream');
  lines.push(contentStream);
  lines.push('endstream');
  lines.push('endobj');

  // Object 5: Font (Courier)
  lines.push('5 0 obj');
  lines.push('<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>');
  lines.push('endobj');

  // Cross-reference table
  const xrefOffset = lines.join('\n').length + 1;
  lines.push('xref');
  lines.push('0 6');
  lines.push('0000000000 65535 f ');
  lines.push(`0000000009 00000 n `);
  lines.push(`0000000062 00000 n `);
  lines.push(`0000000118 00000 n `);
  lines.push(`0000000262 00000 n `);
  lines.push(`0000000345 00000 n `);

  // Trailer
  lines.push('trailer');
  lines.push('<< /Size 6 /Root 1 0 R >>');
  lines.push('startxref');
  lines.push(String(xrefOffset));
  lines.push('%%EOF');

  return Buffer.from(lines.join('\n'), 'ascii');
}
