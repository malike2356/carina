#!/usr/bin/env node
/**
 * Regenerates src/lib/cyber-tools-stub.generated.ts from the Carina backend registry.
 * Run from app.carinaai.uk: node scripts/sync-cyber-tools-stub.mjs
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const coreRoot = join(__dirname, '../../../../02-backends/core.carinaai.uk');
const outputPath = join(__dirname, '../src/lib/cyber-tools-stub.generated.ts');

const json = execFileSync(
  'npx',
  [
    'tsx',
    '-e',
    `import { AIVA_SECURITY_TOOLS } from './src/tools/cyber-tools-registry.ts';
const tools = AIVA_SECURITY_TOOLS.map((t) => ({
  name: t.name,
  category: t.category,
  requiredTier: t.requiredTier,
  binary: t.binary,
  description: t.description,
  triggers: t.triggers,
  upgradeNote: t.upgradeNote ?? null,
}));
console.log(JSON.stringify(tools));`,
  ],
  { cwd: coreRoot, encoding: 'utf8' },
).trim();

const tools = JSON.parse(json);
const source = `/* eslint-disable */
// Generated by scripts/sync-cyber-tools-stub.mjs - do not edit manually.
import type { CyberTool } from './cyber-tools-core';

export const CYBER_TOOL_COUNT = ${tools.length};

export const STATIC_CYBER_TOOLS: CyberTool[] = ${JSON.stringify(tools, null, 2)};
`;

writeFileSync(outputPath, source, 'utf8');
console.log(`[sync-cyber-tools-stub] wrote ${tools.length} tools to ${outputPath}`);
