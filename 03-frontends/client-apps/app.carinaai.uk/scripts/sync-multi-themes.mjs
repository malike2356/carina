#!/usr/bin/env node
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const APP_ROOT = path.join(__dirname, '..');
const THEME_SRC = path.join(APP_ROOT, '..', '..', '..', 'themes', '01-multi-theme-switching');
const THEME_DST = path.join(APP_ROOT, 'public', 'themes', 'multi');
const CATALOG_OUT = path.join(APP_ROOT, 'src', 'lib', 'multi-theme-catalog.generated.ts');

function titleCase(slug) {
  return slug
    .split('-')
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ');
}

function collectThemeEntries(dir) {
  const entries = [];
  for (const file of fs.readdirSync(dir).sort()) {
    if (!file.endsWith('.css') && !file.endsWith('.csss')) continue;
    const normalized = file.endsWith('.csss') ? file.replace(/\.csss$/, '.css') : file;
    const id = normalized.replace(/\.css$/, '');
    if (entries.some((entry) => entry.id === id)) continue;
    entries.push({ id, label: titleCase(id), file: normalized });
  }
  return entries;
}

fs.mkdirSync(THEME_DST, { recursive: true });

let entries = [];
if (fs.existsSync(THEME_SRC)) {
  for (const file of fs.readdirSync(THEME_SRC).sort()) {
    if (!file.endsWith('.css') && !file.endsWith('.csss')) continue;
    const normalized = file.endsWith('.csss') ? file.replace(/\.csss$/, '.css') : file;
    const id = normalized.replace(/\.css$/, '');
    if (entries.some((entry) => entry.id === id)) continue;
    fs.copyFileSync(path.join(THEME_SRC, file), path.join(THEME_DST, normalized));
    entries.push({ id, label: titleCase(id), file: normalized });
  }
} else if (fs.existsSync(THEME_DST)) {
  entries = collectThemeEntries(THEME_DST);
  if (entries.length === 0) {
    console.error(`Theme source not found: ${THEME_SRC}`);
    process.exit(1);
  }
  console.warn(`Theme source not found (${THEME_SRC}); using existing public/themes/multi/`);
} else {
  console.error(`Theme source not found: ${THEME_SRC}`);
  process.exit(1);
}

const bridgeSrc = path.join(APP_ROOT, 'public', 'themes', 'theme-bridge.css');
if (!fs.existsSync(bridgeSrc)) {
  console.warn('theme-bridge.css missing; create it in public/themes/');
}

const catalog = `/* eslint-disable */
// Generated by scripts/sync-multi-themes.mjs. Do not edit by hand.

export interface MultiThemeDefinition {
  id: string;
  label: string;
  file: string;
}

export const MULTI_THEMES: MultiThemeDefinition[] = ${JSON.stringify(entries, null, 2)} as const;

export const MULTI_THEME_IDS = MULTI_THEMES.map((theme) => theme.id);

export const DEFAULT_MULTI_THEME = 'default';
`;

fs.writeFileSync(CATALOG_OUT, catalog);
console.log(`Synced ${entries.length} themes to public/themes/multi/`);
