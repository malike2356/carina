/** Template role title for a worker, when hired from a known template. */
export function templateRoleNameFor(templateId: string | null | undefined): string | null {
  if (!templateId) return null;
  const card = AIVA_ROLE_TEMPLATE_CARDS.find((c) => c.templateId === templateId);
  return card?.roleName ?? null;
}

/**
 * Secondary line under the Aiva's custom name: template title, then short description.
 * Keeps persona/template visible without replacing the display name.
 */
export function workerPersonaSubtitle(worker: {
  templateId?: string | null;
  roleDescription?: string | null;
}): string {
  const templateLabel = templateRoleNameFor(worker.templateId);
  const desc = (worker.roleDescription ?? '').trim();
  const shortDesc = desc
    ? (desc.split(/[.!?\n]/)[0]?.trim() || desc)
    : '';
  const clipped =
    shortDesc.length > 100 ? `${shortDesc.slice(0, 100)}...` : shortDesc;

  if (templateLabel && clipped) {
    if (clipped.toLowerCase().startsWith(templateLabel.toLowerCase())) {
      return clipped;
    }
    return `${templateLabel} · ${clipped}`;
  }
  return templateLabel || clipped || 'AI worker';
}

