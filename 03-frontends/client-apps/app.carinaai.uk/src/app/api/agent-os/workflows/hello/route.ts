import { NextResponse } from 'next/server';
import { createAgentOsDocument } from '@/lib/agent-os-documents';

export const dynamic = 'force-dynamic';

export async function POST(request: Request) {
  const body = (await request.json().catch(() => ({}))) as { brief?: string; business?: string };
  const business = String(body.business ?? '').trim() || 'your business';
  const brief = String(body.brief ?? '').trim() || 'a concise one-page brief';
  const title = `Hello brief: ${business}`;
  const content = `# ${title}

## Goal
${brief}

## Business
${business}

## Snapshot
- Audience: describe who you serve
- Offer: one sentence value
- Next action: ship one workflow from Agent OS

## Checklist
- [ ] Confirm brand voice
- [ ] Pick one channel to publish
- [ ] Open Capabilities and connect anything missing

---
Generated by Carina Agent OS Hello recipe.
`;

  const result = await createAgentOsDocument(title, content);
  if ('error' in result) return result.error;
  return NextResponse.json({ data: result.document, href: `/documents/${result.document!.id}` });
}
