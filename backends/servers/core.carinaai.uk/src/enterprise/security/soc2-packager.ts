import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { collectFramework } from '../../security/compliance/index.js';
import { immutableEnterpriseAudit } from './audit.js';
import { getDrStatus } from './dr.js';
import { buildResidencyStatus } from './residency.js';
import { describeEnterpriseSsoStatus } from './sso.js';
import { describeZeroTrustStatus } from './zero-trust.js';
import { soc2PackagesDir } from './paths.js';
import type { Soc2EvidenceManifest } from './types.js';

function sha256(value: string): string {
  return createHash('sha256').update(value).digest('hex');
}

export async function generateSoc2EvidencePackage(input: {
  from: string;
  to: string;
}): Promise<Soc2EvidenceManifest> {
  const report = await collectFramework('soc2');
  const auditVerification = await immutableEnterpriseAudit.verifyChain();
  const drStatus = await getDrStatus();
  const residency = buildResidencyStatus();
  const sso = describeEnterpriseSsoStatus();
  const zeroTrust = describeZeroTrustStatus();

  const documents: Record<string, unknown> = {
    'summary/report.json': {
      periodFrom: input.from,
      periodTo: input.to,
      controlsTested: Array.isArray(report) ? report[0]?.evidence.length ?? 0 : report.evidence.length,
      auditChainValid: auditVerification.valid,
      drLastTestPassed: drStatus.lastDrTestPassed,
      residencyRegion: residency.region,
      ssoProvidersConfigured: sso.readiness.providersConfigured,
      zeroTrustMtlsEnabled: zeroTrust.mtlsEnabled,
    },
    'cc6_logical_access/sso-status.json': sso,
    'a1_availability/dr-status.json': drStatus,
    'c1_encryption/residency-status.json': residency,
    'cc8_change_management/zero-trust-status.json': zeroTrust,
    'cc4_monitoring/compliance-report.json': report,
    'auditor_readme.md': [
      '# SOC2 Type II evidence package',
      '',
      'This package was generated by Carina Enterprise Security.',
      'Verify file hashes with `carina enterprise security soc2 verify --package <path>`.',
      '',
      `Period: ${input.from} to ${input.to}`,
    ].join('\n'),
  };

  await fs.mkdir(soc2PackagesDir(), { recursive: true });
  const stamp = new Date().toISOString().replace(/[:.]/g, '-');
  const packageDir = path.join(soc2PackagesDir(), `soc2-${stamp}`);
  await fs.mkdir(packageDir, { recursive: true });

  const hashes: Record<string, string> = {};
  for (const [relativePath, payload] of Object.entries(documents)) {
    const body = typeof payload === 'string' ? payload : JSON.stringify(payload, null, 2);
    const target = path.join(packageDir, relativePath);
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, body, 'utf8');
    hashes[relativePath] = sha256(body);
  }

  const manifest: Soc2EvidenceManifest = {
    generatedAt: new Date().toISOString(),
    periodFrom: input.from,
    periodTo: input.to,
    controlCount: Array.isArray(report) ? report[0]?.evidence.length ?? 0 : report.evidence.length,
    documentCount: Object.keys(documents).length,
    packagePath: packageDir,
    hashes,
  };

  await fs.writeFile(
    path.join(packageDir, 'manifest.json'),
    JSON.stringify(manifest, null, 2),
    'utf8',
  );

  return manifest;
}

export async function verifySoc2EvidencePackage(packagePath: string): Promise<{
  valid: boolean;
  missing: string[];
  hashMismatches: string[];
}> {
  const manifestRaw = await fs.readFile(path.join(packagePath, 'manifest.json'), 'utf8');
  const manifest = JSON.parse(manifestRaw) as Soc2EvidenceManifest;
  const missing: string[] = [];
  const hashMismatches: string[] = [];

  for (const [relativePath, expectedHash] of Object.entries(manifest.hashes)) {
    const target = path.join(packagePath, relativePath);
    try {
      const body = await fs.readFile(target, 'utf8');
      const actual = sha256(body);
      if (actual !== expectedHash) hashMismatches.push(relativePath);
    } catch {
      missing.push(relativePath);
    }
  }

  return {
    valid: missing.length === 0 && hashMismatches.length === 0,
    missing,
    hashMismatches,
  };
}
