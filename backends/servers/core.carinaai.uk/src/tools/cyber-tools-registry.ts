export const CYBER_TOOLS: CyberToolDef[] = [...SELF_HOSTED_TOOLS, ...CLOUD_TOOLS, ...MONITOR_TOOLS];

const BY_NAME = new Map(CYBER_TOOLS.map((t) => [t.name, t]));

export function getCyberToolDef(name: string): CyberToolDef | undefined {
  return BY_NAME.get(name);
}

export function listCyberToolNames(): string[] {
  return CYBER_TOOLS.map((t) => t.name);
}
