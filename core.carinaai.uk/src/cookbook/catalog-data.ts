const HF = 'https://huggingface.co';

function gguf(
  id: string,
  displayName: string,
  family: string,
  paramCount: string,
  quantization: string,
  vramGb: number,
  ramGb: number,
  diskGb: number,
  path: string,
  strengths: string[],
  license: string,
  contextWindow: number,
  ollamaTag?: string,
): CatalogEntry {
  return {
    id,
    displayName,
    family,
    paramCount,
    quantization,
    format: 'gguf',
    vramRequiredGb: vramGb,
    ramRequiredGb: ramGb,
    diskGb,
    downloadUrl: `${HF}/${path}/resolve/main/${id}.gguf`,
    serveVia: ['ollama', 'llama.cpp'],
    strengths,
    license,
    contextWindow,
    ollamaTag,
  };
}

