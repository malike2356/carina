export interface SimplePdfObject {
  id: number;
  body: string;
}

/**
 * Build a minimal single-page PDF with calculated byte offsets.
 * Avoids hardcoded startxref values that break when content length changes.
 */
export function buildSimplePdf(objects: SimplePdfObject[]): Buffer {
  const parts: string[] = ['%PDF-1.4'];
  const xrefEntries: Array<{ offset: number; generation: number; inUse: boolean }> = [];

  xrefEntries.push({ offset: 0, generation: 65535, inUse: false });

  for (const obj of objects) {
    xrefEntries.push({
      offset: Buffer.byteLength(parts.join('\n') + '\n', 'ascii'),
      generation: 0,
      inUse: true,
    });
    parts.push(`${obj.id} 0 obj`);
    parts.push(obj.body);
    parts.push('endobj');
  }

  const xrefOffset = Buffer.byteLength(parts.join('\n') + '\n', 'ascii');
  parts.push('xref');
  parts.push(`0 ${objects.length + 1}`);
  parts.push('0000000000 65535 f ');
  for (let i = 1; i <= objects.length; i += 1) {
    const entry = xrefEntries[i];
    if (!entry) continue;
    parts.push(`${String(entry.offset).padStart(10, '0')} ${String(entry.generation).padStart(5, '0')} n `);
  }
  parts.push('trailer');
  parts.push(`<< /Size ${objects.length + 1} /Root 1 0 R >>`);
  parts.push('startxref');
  parts.push(String(xrefOffset));
  parts.push('%%EOF');

  return Buffer.from(parts.join('\n'), 'ascii');
}

export function buildTextPagePdf(lines: string[]): Buffer {
  const contentLines: string[] = [
    'BT',
    '/F1 10 Tf',
    '72 750 Td',
    `(Labyrinth Scout Export - ${new Date().toISOString().slice(0, 10)}) Tj`,
    '0 -18 Td',
    '(Generated by Labyrinth Scout Console) Tj',
    '0 -24 Td',
    '/F1 8 Tf',
  ];

  for (const line of lines.map((row) => row.slice(0, 100))) {
    const escaped = line
      .replace(/\\/g, '\\\\')
      .replace(/\(/g, '\\(')
      .replace(/\)/g, '\\)');
    contentLines.push(`(${escaped}) Tj`);
    contentLines.push('0 -12 Td');
  }
  contentLines.push('ET');

  const contentStream = contentLines.join('\n');

  return buildSimplePdf([
    { id: 1, body: '<< /Type /Catalog /Pages 2 0 R >>' },
    { id: 2, body: '<< /Type /Pages /Kids [3 0 R] /Count 1 >>' },
    {
      id: 3,
      body: [
        '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792]',
        '   /Contents 4 0 R',
        '   /Resources << /Font << /F1 5 0 R >> >>',
        '>>',
      ].join('\n'),
    },
    {
      id: 4,
      body: `<< /Length ${Buffer.byteLength(contentStream, 'ascii')} >>\nstream\n${contentStream}\nendstream`,
    },
    { id: 5, body: '<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>' },
  ]);
}
